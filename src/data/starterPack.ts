import type { GrowthProfile } from '../domain/stats.js';

function growth(hp: number, aether: number, atk: number, def: number, agi: number, luck: number): GrowthProfile {
  return {
    maxHp: { base: hp, gain: hp * 0.11, curve: 1.05 },
    maxAether: { base: aether, gain: aether * 0.12, curve: 1.02 },
    attack: { base: atk, gain: atk * 0.09 },
    defense: { base: def, gain: def * 0.08 },
    agility: { base: agi, gain: agi * 0.07 },
    luck: { base: luck, gain: 0.4 },
  };
}

